import { redactDeep } from '../privacy/redact';
import type { Assessment } from '../assessment/engine';
import { STATE_LABELS } from '../shared/types';
import { TOOL_VERSION } from './json';

export function buildTextReport(input: Assessment, generatedAt: Date = new Date()): string {
  const a = redactDeep(input);
  const L: string[] = [];
  L.push(`# PHP2Shell exposure assessment`, '');
  L.push(`- **Target origin:** ${a.target.requestedOrigin}`);
  if (a.target.redirected) L.push(`- **Final origin after redirect:** ${a.target.finalOrigin}${a.target.hostChanged ? ' (different host - not assessed)' : ''}`);
  L.push(`- **Assessed at:** ${a.assessedAt}`);
  L.push(`- **Report generated by:** PHP2Shell Detector ${TOOL_VERSION} at ${generatedAt.toISOString()}`, '');
  L.push(`## Assessment: ${STATE_LABELS[a.state]}`, '', `**${a.headline}** (rule ${a.ruleId})`, '');
  for (const r of a.rationale) L.push(`- ${r}`);
  L.push('', `**Confidence:** ${a.confidence.level} - a qualitative label, not a probability. ${a.confidence.basis.join(' ')}`, '');
  if (a.warnings.length) {
    L.push('## Warnings', '');
    for (const w of a.warnings) L.push(`- ${w}`);
    L.push('');
  }
  L.push('## Observed evidence', '');
  for (const e of a.evidence) {
    L.push(`### ${e.summary}`);
    L.push(`- Source: ${e.source.type} \`${e.source.name}\` @ ${e.source.origin}`);
    L.push(`- Collected: ${e.collectedAt}`);
    L.push(`- Type: ${e.directness}${e.versionProvenance ? ` (version ${e.versionProvenance})` : ''}; reliability **${e.reliability}** - ${e.reliabilityReason}`);
    L.push(`- Observed value: \`${e.value}\``);
    L.push(`- Does not prove: ${e.doesNotProve.join('; ')}`, '');
  }
  if (a.ownerErrors.length) {
    L.push('## Rejected owner report', '');
    for (const e of a.ownerErrors) L.push(`- ${e}`);
    L.push('');
  }
  L.push('## Relevant CVEs', '');
  if (a.cves.length === 0) L.push('Advisory data unavailable.');
  for (const c of a.cves) L.push(`- **${c.id}**${c.ghsa ? ` (${c.ghsa})` : ''}: ${c.summary}`);
  if (a.fixedReleases.length) L.push('', `Fixed upstream releases: ${a.fixedReleases.map((f) => f.fixedIn).join(', ')}. Vendor backports may apply to packaged builds.`);
  L.push(
    '',
    a.advisory.available
      ? `Advisory dataset \`${a.advisory.datasetId}\`, last verified ${a.advisory.verifiedAt}${a.advisory.stale ? ' (STALE)' : ''}.`
      : `Advisory data unavailable: ${a.advisory.note}`,
    '',
  );
  L.push('## Unverified assumptions', '');
  for (const u of a.unknowns) L.push(`- ${u}`);
  L.push('', '## Recommended actions', '');
  a.nextSteps.forEach((s, i) => L.push(`${i + 1}. **${s.title}** - ${s.detail}`));
  L.push('', '## Sources', '');
  for (const r of a.references) L.push(`- ${r.publisher}: [${r.title}](${r.url}) (checked ${r.checkedAt})`);
  L.push('', '---', '_Passive, public-response evidence only. This is not proof that a server is vulnerable or safe. Cookies, credentials, authorization headers and response bodies are never included._', '');
  return L.join('\n');
}
